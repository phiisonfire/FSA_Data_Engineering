-- CALCULATE TOTAL QUANTITY OF PARTS OF EACH ORDER
-- group by
SELECT
    ORDERKEY,
    SUM(QUANTITY) AS TOTAL_QTY
FROM LineItem
GROUP BY ORDERKEY
ORDER BY ORDERKEY; -- 1,500,000 ROWS


-- using subquery
SELECT DISTINCT 
       LI.ORDERKEY, 
       (SELECT SUM(LI2.QUANTITY) 
        FROM LineItem LI2 
        WHERE LI2.ORDERKEY = LI.ORDERKEY) AS TOTAL_QTY
FROM LineItem LI
ORDER BY LI.ORDERKEY; -- 1,500,000 ROWS

-- using window function
SELECT DISTINCT 
    ORDERKEY,
    SUM(QUANTITY) OVER (PARTITION BY ORDERKEY) AS TOTAL_QTY
FROM LineItem
ORDER BY ORDERKEY; -- 1,500,000 rows

-- CALCULATE TOTAL QUANTITY OF PARTS A CUSTOMER ORDERED
-- having
SELECT C.CUSTKEY, 
       SUM(LI.QUANTITY) AS TOTAL_QTY
FROM Customer C
INNER JOIN Orders O ON C.CUSTKEY = O.CUSTKEY
INNER JOIN LineItem LI ON O.ORDERKEY = LI.ORDERKEY
GROUP BY C.CUSTKEY
HAVING SUM(LI.QUANTITY) > 100
ORDER BY C.CUSTKEY; -- 99,974 ROWS

-- CTE
WITH AggregatedData AS (
    SELECT DISTINCT C.CUSTKEY, 
           SUM(LI.QUANTITY) OVER (PARTITION BY C.CUSTKEY) AS TOTAL_QTY
    FROM Customer C
    INNER JOIN Orders O ON C.CUSTKEY = O.CUSTKEY
    INNER JOIN LineItem LI ON O.ORDERKEY = LI.ORDERKEY
)
SELECT CUSTKEY, TOTAL_QTY
FROM AggregatedData
WHERE TOTAL_QTY > 100
ORDER BY CUSTKEY; -- 99,974 ROWS

