CREATE TABLE Orders (
    ORDERKEY INT PRIMARY KEY,
    CUSTKEY INT,
    ORDERSTATUS CHAR(1),
    TOTALPRICE DECIMAL(15, 2),
    ORDERDATE DATE,
    ORDERPRIORITY CHAR(15),
    CLERK CHAR(15),
    SHIPPRIORITY INT,
    COMMENT VARCHAR(79),
    CONSTRAINT FK_Orders_Customer FOREIGN KEY (CUSTKEY) REFERENCES Customer(CUSTKEY)
);

BULK INSERT Orders
FROM '/data/orders.tbl'
WITH (
    FIELDTERMINATOR = '|',
    ROWTERMINATOR = '0x0A',
    FIRSTROW = 1
);

CREATE TABLE LineItem (
    ORDERKEY INT,
    PARTKEY INT,
    SUPPKEY INT,
    LINENUMBER INT,
    QUANTITY DECIMAL(15, 2),
    EXTENDEDPRICE DECIMAL(15, 2),
    DISCOUNT DECIMAL(15, 2),
    TAX DECIMAL(15, 2),
    RETURNFLAG CHAR(1),
    LINESTATUS CHAR(1),
    SHIPDATE DATE,
    COMMITDATE DATE,
    RECEIPTDATE DATE,
    SHIPINSTRUCT CHAR(25),
    SHIPMODE CHAR(10),
    COMMENT VARCHAR(44),
    PRIMARY KEY (ORDERKEY, LINENUMBER),
    CONSTRAINT FK_LineItem_Order FOREIGN KEY (ORDERKEY) REFERENCES Orders(ORDERKEY)
);

BULK INSERT LineItem
FROM '/data/lineitem.tbl'
WITH (
    FIELDTERMINATOR = '|',
    ROWTERMINATOR = '0x0A',
    FIRSTROW = 1
);

